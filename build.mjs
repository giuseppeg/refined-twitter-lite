import { readFileSync, writeFileSync } from "node:fs";

// Bundle the same initializers and entry used by the extension.
const old = readFileSync(new URL("index.old.js", import.meta.url), "utf8");
const current = readFileSync(new URL("index.new.js", import.meta.url), "utf8");
const entry = readFileSync(new URL("entry.js", import.meta.url), "utf8");
const metadataEnd = old.indexOf("// ==/UserScript==") + "// ==/UserScript==".length;
const metadata = old.slice(0, metadataEnd)
  .replace("// @match https://mobile.twitter.com/*", "// @match https://mobile.twitter.com/*\n// @match https://x.com/*\n// @match https://tweetdeck.twitter.com/*");
writeFileSync(new URL("index.user.js", import.meta.url), `${metadata}\n// Generated by node build.mjs. Edit the source files instead.\n${old.slice(metadataEnd).trimStart()}\n${current}\n${entry}`);
